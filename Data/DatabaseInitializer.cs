using System.Data.Common;
using Microsoft.EntityFrameworkCore;

namespace PocketLedger.Data;

public static class DatabaseInitializer
{
    public static async Task InitializeAsync(IServiceProvider services)
    {
        await using var scope = services.CreateAsyncScope();
        var accounts = scope.ServiceProvider.GetRequiredService<AccountsDbContext>();
        var finance = scope.ServiceProvider.GetRequiredService<FinanceDbContext>();

        await accounts.Database.EnsureCreatedAsync();
        if (accounts.Database.IsNpgsql())
        {
            await finance.Database.ExecuteSqlRawAsync("""
                CREATE SCHEMA IF NOT EXISTS "finance";
                CREATE TABLE IF NOT EXISTS "finance"."Transactions" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "UserId" text NOT NULL, "Date" timestamp without time zone NOT NULL,
                    "Description" character varying(80) NOT NULL, "Category" character varying(40) NOT NULL,
                    "Type" character varying(10) NOT NULL, "Amount" numeric(12,2) NOT NULL
                );
                CREATE TABLE IF NOT EXISTS "finance"."Budgets" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "UserId" text NOT NULL, "YearMonth" character varying(7) NOT NULL,
                    "Category" character varying(40) NOT NULL, "LimitAmount" numeric(12,2) NOT NULL
                );
                CREATE TABLE IF NOT EXISTS "finance"."BankConnections" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "UserId" text NOT NULL, "Provider" text NOT NULL, "ProviderCardId" text NULL,
                    "DisplayName" text NOT NULL, "Network" text NULL, "LastFour" text NULL,
                    "CardType" text NULL, "ConnectedAt" timestamp with time zone NOT NULL
                );
                CREATE TABLE IF NOT EXISTS "finance"."BankLinkStates" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "UserId" text NOT NULL, "StateHash" text NOT NULL,
                    "ExpiresAt" timestamp with time zone NOT NULL, "ConsumedAt" timestamp with time zone NULL
                );
                CREATE TABLE IF NOT EXISTS "finance"."DataProtectionKeys" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "FriendlyName" text NULL, "Xml" text NULL
                );
                CREATE INDEX IF NOT EXISTS "IX_Transactions_UserId_Date" ON "finance"."Transactions" ("UserId", "Date");
                CREATE INDEX IF NOT EXISTS "IX_Budgets_UserId_YearMonth" ON "finance"."Budgets" ("UserId", "YearMonth");
                CREATE INDEX IF NOT EXISTS "IX_BankConnections_UserId" ON "finance"."BankConnections" ("UserId");
                CREATE UNIQUE INDEX IF NOT EXISTS "IX_BankLinkStates_StateHash" ON "finance"."BankLinkStates" ("StateHash");
                """);
            return;
        }

        await finance.Database.EnsureCreatedAsync();

        await finance.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "DataProtectionKeys" (
                "Id" INTEGER NOT NULL CONSTRAINT "PK_DataProtectionKeys" PRIMARY KEY AUTOINCREMENT,
                "FriendlyName" TEXT NULL,
                "Xml" TEXT NULL
            );
            CREATE TABLE IF NOT EXISTS "BankConnections" (
                "Id" INTEGER NOT NULL CONSTRAINT "PK_BankConnections" PRIMARY KEY AUTOINCREMENT,
                "UserId" TEXT NOT NULL, "Provider" TEXT NOT NULL, "ProviderCardId" TEXT NULL, "DisplayName" TEXT NOT NULL,
                "Network" TEXT NULL, "LastFour" TEXT NULL, "CardType" TEXT NULL,
                "ConnectedAt" TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS "IX_BankConnections_UserId" ON "BankConnections" ("UserId");
            CREATE TABLE IF NOT EXISTS "BankLinkStates" (
                "Id" INTEGER NOT NULL CONSTRAINT "PK_BankLinkStates" PRIMARY KEY AUTOINCREMENT,
                "UserId" TEXT NOT NULL, "StateHash" TEXT NOT NULL, "ExpiresAt" TEXT NOT NULL, "ConsumedAt" TEXT NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_BankLinkStates_StateHash" ON "BankLinkStates" ("StateHash");
            """);

        // Keep legacy rows without owners isolated; registrations never claim them.
        await finance.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "Budgets" (
                "Id" INTEGER NOT NULL CONSTRAINT "PK_Budgets" PRIMARY KEY AUTOINCREMENT,
                "YearMonth" TEXT NOT NULL,
                "Category" TEXT NOT NULL,
                "LimitAmount" TEXT NOT NULL,
                "UserId" TEXT NULL
            );
            """);

        await EnsureColumnAsync(finance, "Transactions", "UserId");
        await EnsureColumnAsync(finance, "Budgets", "UserId");
        await finance.Database.ExecuteSqlRawAsync(
            "CREATE INDEX IF NOT EXISTS \"IX_Transactions_UserId_Date\" ON \"Transactions\" (\"UserId\", \"Date\");");
        await finance.Database.ExecuteSqlRawAsync(
            "CREATE INDEX IF NOT EXISTS \"IX_Budgets_UserId_YearMonth\" ON \"Budgets\" (\"UserId\", \"YearMonth\");");
    }

    private static async Task EnsureColumnAsync(DbContext context, string table, string column)
    {
        var connection = context.Database.GetDbConnection();
        await connection.OpenAsync();
        try
        {
            await using var command = connection.CreateCommand();
            command.CommandText = $"PRAGMA table_info(\"{table}\");";
            await using var reader = await command.ExecuteReaderAsync();
            var found = false;
            while (await reader.ReadAsync())
            {
                if (string.Equals(reader.GetString(1), column, StringComparison.OrdinalIgnoreCase))
                {
                    found = true;
                    break;
                }
            }

            await reader.CloseAsync();
            if (!found)
            {
                var sql = (table, column) switch
                {
                    ("Transactions", "UserId") => "ALTER TABLE \"Transactions\" ADD COLUMN \"UserId\" TEXT NULL;",
                    ("Budgets", "UserId") => "ALTER TABLE \"Budgets\" ADD COLUMN \"UserId\" TEXT NULL;",
                    _ => throw new InvalidOperationException("Unexpected database schema update.")
                };
                await context.Database.ExecuteSqlRawAsync(sql);
            }
        }
        finally
        {
            await connection.CloseAsync();
        }
    }
}
